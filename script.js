/* =========================
   ELEMENTE
========================= */

const filtre = document.querySelector(".filters");
const grila = document.querySelector(".products-grid");
const cartCount = document.querySelector(".cart-count");
const cartItems = document.querySelector(".cart-items");
const cartTotal = document.querySelector(".cart-total");
const cartPanel = document.querySelector(".cart-panel");
const overlay = document.querySelector(".overlay");

let activeCategory = "Toate";
let cart = [];


/* =========================
   CATEGORII
========================= */

function categories() {
  return [
    "Toate",
    "Botez",
    "Nunta",
    "Nunta-Botez",
    "Marturii",
    "Cani",
    "Pahare",
    "Toppere",
    "Carti",
    "Party",
    "Set Mot"
  ];
}


/* =========================
   PRET
========================= */

function money(value) {
  return `${value.toFixed(2).replace(".", ",")} lei`;
}


/* =========================
   AFISARE CATEGORII
========================= */

function renderCategories() {
  if (!filtre) return;

  filtre.innerHTML = categories()
    .map(category => `
      <button
        class="filter-btn ${category === activeCategory ? "active" : ""}"
        onclick="setCategory('${category}')"
      >
        ${category}
      </button>
    `)
    .join("");
}


/* =========================
   SCHIMBARE CATEGORIE
========================= */

function setCategory(category) {
  activeCategory = category;
  renderCategories();
  renderProducts();
}


/* =========================
   AFISARE PRODUSE
========================= */

function renderProducts() {
  if (!grila) return;

  const list =
    activeCategory === "Toate"
      ? products
      : products.filter(
          product => product.categorie === activeCategory
        );

  if (list.length === 0) {
    grila.innerHTML = `
      <div class="empty-products">
        Nu există produse în această categorie momentan.
      </div>
    `;
    return;
  }

  grila.innerHTML = list
    .map(product => {
      const imagini = product.poze || [product.poza];

      return `
        <article class="product-card">

          <div class="product-photo">
            <img
              src="${imagini[0]}"
              alt="${product.nume}"
              data-product-id="${product.id}"
            >
          </div>

          <div class="product-info">

            <div class="product-category">
              ${product.categorie}
            </div>

            <div class="product-name">
              ${product.nume}
            </div>

            <div class="product-price">
              ${money(product.pret)}
            </div>

            <div class="product-actions">

  ${product.categorie === "Set Mot"
    ? `
      <button
        class="add-cart"
        onclick="openSetMotCustomizer(${product.id})"
      >
        Personalizează
      </button>
    `
    : `
      <button
        class="add-cart"
        onclick="addToCart(${product.id})"
      >
        Adaugă în coș
      </button>
    `
  }

  <button
    class="fav"
    onclick="this.classList.toggle('active')"
  >
    ♡
  </button>

</div>

            </div>

          </div>

        </article>
      `;
    })
    .join("");
}


/* =========================
   COS
========================= */

function addToCart(productId) {
  const product = products.find(
    product => product.id === productId
  );

  if (!product) return;

  cart.push(product);

  renderCart();
  openCart();
}


function removeFromCart(index) {
  cart.splice(index, 1);
  renderCart();
}


function renderCart() {
  if (cartCount) {
    cartCount.textContent = cart.length;
  }

  if (!cartItems || !cartTotal) return;

  if (cart.length === 0) {
    cartItems.innerHTML = `
      <p class="empty-cart">
        Coșul este gol.
      </p>
    `;

    cartTotal.textContent = "0,00 lei";
    return;
  }

  cartItems.innerHTML = cart
    .map(
      (product, index) => `
        <div class="cart-item">

          <div>
            <strong>${product.nume}</strong>
            <span>${money(product.pret)}</span>
          </div>

          <button onclick="removeFromCart(${index})">
            ×
          </button>

        </div>
      `
    )
    .join("");

  const total = cart.reduce(
    (sum, product) => sum + product.pret,
    0
  );

  cartTotal.textContent = money(total);
}


