function unitPriceForQuantity(product, quantity = 1) {
  const qty = Math.max(1, Number(quantity) || 1);
  if (Array.isArray(product?.tarifeCantitate)) {
    const tier = product.tarifeCantitate.find(item => qty >= item.min && (item.max === null || qty <= item.max));
    if (tier) return tier.pret;
  }
  return product?.pret || 0;
}

function addToCart(productId, quantity = 1, personalizare = null) {
  const product = products.find(item => item.id === Number(productId));
  let qty = Number(quantity);

  if (!product) return;
  const minimum = isMin25Invitation(product) ? INVITATION_MINIMUM : 1;
  if (isMin25Invitation(product) && qty < minimum) {
    alert("Comanda minimă pentru acest produs este de 25 de bucăți.");
    const quantityEl = document.getElementById(`qty-${productId}`);
    if (quantityEl) quantityEl.textContent = String(minimum);
    return;
  }
  if (!Number.isInteger(qty) || qty < 1) {
    alert("Introdu un număr valid de bucăți.");
    return;
  }

  cart.push({ ...product, pret: unitPriceForQuantity(product, qty), quantity: qty, ...(personalizare ? { personalizare } : {}) });
  renderCart();
  openCart();
}

function removeFromCart(index) {
  cart.splice(index, 1);
  renderCart();
}

function changeCartQuantity(index, quantity) {
  const qty = Number(quantity);
  if (!cart[index]) return;
  const minimum = isMin25Invitation(cart[index]) ? INVITATION_MINIMUM : 1;
  if (!Number.isInteger(qty) || qty < minimum) {
    alert(isMin25Invitation(cart[index]) ? "Comanda minimă pentru acest produs este de 25 de bucăți." : "Cantitatea minimă este 1.");
    renderCart();
    return;
  }
  cart[index].quantity = qty;
  cart[index].pret = unitPriceForQuantity(cart[index], qty);
  renderCart();
}

